public enum L10n {
  nonisolated(unsafe) public static var setting: String = "system"

  public static var lang: Lang {
    switch setting {
    case "de": return .de
    case "en": return .en
    default:
      let first = Locale.preferredLanguages.first ?? "en"
      return first.hasPrefix("de") ? .de : .en
    }
  }

  public static func string(_ key: String) -> String {
    if let s = table[lang]?[key] { return s }
    if let s = table[.en]?[key] { return s }
    return key
  }

  public static func list(_ key: String) -> [String] {
    if let l = lists[lang]?[key] { return l }
    return lists[.en]?[key] ?? []
