public func T(_ key: String, _ args: Any...) -> String {
  var s = L10n.string(key)
  for (i, a) in args.enumerated() {
    s = s.replacingOccurrences(of: "{\(i)}", with: "\(a)")
  }
  return s
}

public func plural(_ n: Int, _ key: String) -> String {
  let forms = L10n.list("plural.\(key)")
  guard forms.count >= 2 else { return "\(n) \(key)" }
  return "\(n) \(n == 1 ? forms[0] : forms[1])"
}
