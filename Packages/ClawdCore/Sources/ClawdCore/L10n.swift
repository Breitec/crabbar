import Foundation

public enum Lang: String, Codable, CaseIterable, Sendable {
  case de, en

  public var locale: Locale { Locale(identifier: self == .de ? "de_DE" : "en_US") }
  public var displayName: String { self == .de ? "Deutsch" : "English" }
}

